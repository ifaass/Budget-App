const MONTHS_SHORT = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

export function monthKey(date: Date): string {
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}`;
}

export function shiftMonth(ym: string, delta: number): string {
  const [year, month] = ym.split("-").map(Number);
  const next = new Date(year, month - 1 + delta, 1);
  return monthKey(next);
}

export function formatMonth(ym: string, lang: Lang): string {
  const [year, month] = ym.split("-").map(Number);
  return `${MONTHS[lang][month - 1]} ${year}`;
}

export function formatDay(iso: string, lang: Lang): string {
  const [year, month, day] = iso.split("-").map(Number);
  const name = lang === "en" ? MONTHS_SHORT[month - 1] : MONTHS[lang][month - 1];
  return `${day} ${name} ${year}`;
}

export function todayISO(): string {
  const date = new Date();
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, "0")}-${String(date.getDate()).padStart(2, "0")}`;
}

export function categoryLabel(category: Category | undefined, lang: Lang): string {
  if (!category) return t(lang, "uncategorized");
  if (category.name && category.name.trim()) return category.name.trim();
  if (category.nameKey) return t(lang, category.nameKey);
  return t(lang, "uncategorized");
}
